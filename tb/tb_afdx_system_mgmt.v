 // expected payload model: byte k of a frame = (vl*37 + len*11 + k*3) & 0xff
 function [7:0] payload_byte;
  input integer vl_in;
  input integer len_in;
  input integer idx_in;
  begin
   payload_byte = (vl_in * 37 + len_in * 11 + idx_in * 3) & 8'hFF;
  end
 endfunction

 // full_drops 64 -> 32 saturation (same rule as the wrapper)
 function [31:0] sat32;
  input [63:0] value;
  begin
   sat32 = (value[63:32] != 32'd0) ? 32'hFFFF_FFFF : value[31:0];
  end
 endfunction

