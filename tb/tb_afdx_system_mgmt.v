`timescale 1ns/1ps
// tb_afdx_system_mgmt -- self-checking integration testbench for
// afdx_system_mgmt_top (management plane + full AFDX system data path).
//
// Scenario
//   * power-on reset, wait for the data path / receiver to initialise;
//   * read VERSION / ID / STATUS over the management bus;
//   * prove external run is forwarded (sys_run = ext_run OR mgmt run);
//   * write the BAG shadow and commit it twice (BAG exp 1 then 0); each commit
//     must program VL0..3 of the data path through the wrapper;
//   * start the system from the management run bit only, enable the application;
//   * send 16 application frames (4 VL x lengths 1/17/63/1471), loop the
//     physical line back into both receive networks and check every delivered
//     payload byte / SN / length / VL;
//   * send one 17th frame whose looped-back line bytes are corrupted on both
//     networks, so the receive MACs report bad FCS and drop it;
//   * take a management counter snapshot (CTRL[1]) and read delivered /
//     rejected / full_drops / bad_fcs / tx frames back, comparing them with the
//     live data-path counters (and with the expected scenario numbers);
//   * check the management RTC follows the data-path monotonic_time;
//   * run two SNMPv1 GETs through the direct UDP-payload test port and one GET
//     whose request frame is sent through the application/RX path and routed
//     into the SNMP agent by the wrapper, comparing each response byte-for-byte
//     with the vectors generated by scripts/mgmt/gen_system_mgmt_vectors.py.
//
// PASS text: TEST_PASS tb_afdx_system_mgmt delivered=16 rejected=16 bad_fcs=2
//            snap_tx=17 snmp_direct=2 snmp_rx=1 checks=N errors=0
// Failure prints TEST_FAIL code=<n>; the runner maps any TEST_FAIL to exit 1.
//
// Scope: behavioural simulation only; no synthesis / STA / E5 involvement.
