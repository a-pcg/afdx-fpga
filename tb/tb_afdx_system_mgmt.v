 initial begin clk = 1'b0; forever #5 clk = ~clk; end

 // ------------------------------------------------------------------
 // Physical-line loopback (both receive networks see the transmit line)
 // The 17th frame has exactly one payload byte corrupted on both networks.
 // ------------------------------------------------------------------
 always @* begin
  rx_line_data_a  = tx_line_data ^ (corrupt_now ? 8'h01 : 8'h00);
  rx_line_data_b  = tx_line_data ^ (corrupt_now ? 8'h01 : 8'h00);
  rx_line_valid_a = tx_line_valid;
  rx_line_valid_b = tx_line_valid;
  rx_line_error_a = 1'b0;
  rx_line_error_b = 1'b0;
 end

 always @(posedge clk) begin
  if (reset) begin
   tb_tx_byte_idx <= 0;
   tb_sfd_seen    <= 0;
  end else begin
   if (sfd_pulse)                     tb_sfd_seen <= tb_sfd_seen + 1;
   if (tx_line_valid && tx_byte_ce)   tb_tx_byte_idx <= tb_tx_byte_idx + 1;
   else if (!tx_line_valid)           tb_tx_byte_idx <= 0;
  end
 end

 // ------------------------------------------------------------------
 // Helpers
 // ------------------------------------------------------------------
 task fail_msg;
  input integer code;
  begin
   errors = errors + 1;
   $display("TEST_FAIL code=%0d at %0d", code, $time);
  end
 endtask

 task check;
  input cond;
  input integer code;
  begin
   checks = checks + 1;
   if (!cond) fail_msg(code);
  end
 endtask


 // Management bus write: one request, ready one cycle later (mgmt_regs contract).
 task bus_write;
  input [15:0] a;
  input [31:0] d;
  begin
   @(negedge clk); mgmt_addr = a; mgmt_wdata = d; mgmt_we = 1'b1; mgmt_re = 1'b0;
   @(posedge clk); #1;
   check(mgmt_ready === 1'b1, 10);
   @(negedge clk); mgmt_we = 1'b0;
   @(posedge clk); #1;
  end
 endtask

 task bus_read;
  input [15:0] a;
  begin
   @(negedge clk); mgmt_addr = a; mgmt_wdata = 32'd0; mgmt_we = 1'b0; mgmt_re = 1'b1;
   @(posedge clk); #1;
   check(mgmt_ready === 1'b1, 11);
   rd = mgmt_rdata;
   rd_err = mgmt_error;
   @(negedge clk); mgmt_re = 1'b0;
   @(posedge clk); #1;
  end
 endtask

 task bus_read_expect;
  input [15:0] a;
  input [31:0] exp;
  input integer code;
  begin
   bus_read(a);
   check(rd === exp, code);
  end
 endtask

 // Wait until the management BAG programming sequence completed count times.
 task wait_cfg_done;
  input integer count;
  begin
   wait_i = 0;
   while ((cfg_done_seen < count) && (wait_i < 400000)) begin
    @(negedge clk);
    wait_i = wait_i + 1;
   end
   check(cfg_done_seen >= count, 20);
  end
 endtask

 // Send one application frame. tbl_case >= 0 sends the SNMP vector bytes of
 // that case instead of the synthetic payload pattern.
 task send_frame;
  input integer vl_in;
  input integer len_in;
  input integer tbl_case;
  integer b;
  reg accepted;
  begin
   app_vl     = vl_in[6:0];
   app_length = len_in[11:0];
   @(negedge clk); app_msg_valid = 1'b1;
   accepted = 1'b0; wait_i = 0;
   while (!accepted && (wait_i < 400000)) begin
    @(posedge clk);
    accepted = app_msg_ready;
    wait_i = wait_i + 1;
   end
   check(accepted, 30);
   @(negedge clk); app_msg_valid = 1'b0;
   for (b = 0; b < len_in; b = b + 1) begin
    if (tbl_case >= 0)
     app_data = smg_req_bytes[smg_req_off[tbl_case] + b];
    else
     app_data = payload_byte(vl_in, len_in, b);
    app_valid = 1'b1;
    app_last  = (b == (len_in - 1));
    accepted = 1'b0; wait_i = 0;
    while (!accepted && (wait_i < 400000)) begin
     @(posedge clk);
     accepted = app_ready;
     wait_i = wait_i + 1;
    end
    check(accepted, 31);
    @(negedge clk);
   end
   app_valid = 1'b0; app_last = 1'b0;
   wait_i = 0;
   while (!app_rsp_valid && (wait_i < 400000)) begin
    @(negedge clk);
    wait_i = wait_i + 1;
   end
   check(app_rsp_valid, 32);
   check(app_rsp_status === 4'd0, 33);
   @(negedge clk); app_rsp_ready = 1'b1;
   @(negedge clk); app_rsp_ready = 1'b0;
   sent_frames = sent_frames + 1;
  end
 endtask

 task wait_delivery;
  input integer target;
  begin
   wait_i = 0;
   while (((delivered_frames < target) || (rx_frames < target)) && (wait_i < 4000000)) begin
    @(negedge clk);
    wait_i = wait_i + 1;
   end
   check(delivered_frames >= target, 40);
   check(rx_frames >= target, 41);
  end
 endtask

 // Feed one SNMP request through the direct UDP-payload test port.
 task snmp_direct;
  input integer case_i;
  integer b;
  begin
   for (b = 0; b < smg_req_len[case_i]; b = b + 1) begin
    @(negedge clk);
    snmp_s_valid = 1'b1;
    snmp_s_data  = smg_req_bytes[smg_req_off[case_i] + b];
    snmp_s_sop   = (b == 0);
    snmp_s_eop   = (b == (smg_req_len[case_i] - 1));
    @(posedge clk); #1;
   end
   @(negedge clk); snmp_s_valid = 1'b0; snmp_s_sop = 1'b0; snmp_s_eop = 1'b0;
  end
 endtask

 // Capture one SNMP response and compare it byte-for-byte with the vectors.
 task snmp_expect;
  input integer case_i;
  integer n;
  integer b;
  reg started;
  reg done;
  reg [7:0] got [0:255];
  begin
   n = 0; started = 1'b0; done = 1'b0; wait_i = 0;
   while (!done && (wait_i < 400000)) begin
    @(negedge clk);
    if (snmp_m_valid) begin
     if (!started) begin
      check(snmp_m_sop === 1'b1, 50);
      started = 1'b1;
     end
     got[n] = snmp_m_data;
     n = n + 1;
     if (snmp_m_eop) done = 1'b1;
    end
    wait_i = wait_i + 1;
   end
   check(done === 1'b1, 51);
   check(n === smg_exp_len[case_i], 52);
   for (b = 0; b < smg_exp_len[case_i]; b = b + 1) begin
    if (b < n) check(got[b] === smg_exp_bytes[smg_exp_off[case_i] + b], 53);
   end
  end
 endtask

 // ------------------------------------------------------------------
 // Delivery checker on the RX application stream.
 // ------------------------------------------------------------------
 always @(posedge clk) begin
  if (!reset && rx_check_en && rx_valid && rx_ready_r) begin
   if (rx_idx == 0) begin
    rx_exp_len = rx_len;
    rx_exp_vl  = rx_vl;
   end
   if (rx_len !== rx_exp_len)       fail_msg(100);
   if (rx_vl !== rx_exp_vl)         fail_msg(101);
   if (rx_data !== payload_byte(rx_exp_vl, rx_exp_len, rx_idx)) fail_msg(102);
   if (rx_sn !== vl_sn[rx_exp_vl])  fail_msg(103);
   rx_idx = rx_idx + 1;
   if (rx_last) begin
    if (rx_idx !== rx_exp_len) fail_msg(104);
    vl_sn[rx_exp_vl] = vl_sn[rx_exp_vl] + 8'd1;
    rx_frames = rx_frames + 1;
    rx_idx = 0;
   end
  end
 end

 // Management-programming observation: while a management BAG sequence owns the
 // configuration port, an external cfg request must be rejected, not accepted.
 always @(posedge clk) begin
  if (!reset && cfg_done) cfg_done_seen = cfg_done_seen + 1;
  if (!reset && cfg_busy && ext_cfg_valid) begin
   if (cfg_reject !== 1'b1) fail_msg(120);
   cfg_reject_seen = cfg_reject_seen + 1;
  end
 end

 // ------------------------------------------------------------------
 // Timeout guard: watchdog in clock cycles (2,000,000 clocks = 20 ms).
 // A long #delay is avoided here because the Verilator 5.006 build shipped
 // with this project's toolchain mis-schedules very long delays.
 // ------------------------------------------------------------------
 integer watchdog;
 initial watchdog = 0;

 always @(posedge clk) begin
  if (reset) watchdog = 0;
  else begin
   watchdog = watchdog + 1;
   if (watchdog == 2000000) begin
    $display("TEST_FAIL global timeout at %0d", $time);
    $finish;
   end
  end
 end

 // ------------------------------------------------------------------
 // Main stimulus
 // ------------------------------------------------------------------
 initial begin
  checks = 0; errors = 0; wait_i = 0; sent_frames = 0;
  cfg_done_seen = 0; cfg_reject_seen = 0;
  rx_frames = 0; rx_idx = 0; rx_exp_len = 16'd0; rx_exp_vl = 3'd0;
  rx_check_en = 1'b1; corrupt_en = 1'b0;
  for (vl = 0; vl < 4; vl = vl + 1) vl_sn[vl] = 8'd0;

  reset = 1'b1;
  mgmt_addr = 16'd0; mgmt_wdata = 32'd0; mgmt_we = 1'b0; mgmt_re = 1'b0; mgmt_snap = 1'b0;
  snmp_s_valid = 1'b0; snmp_s_data = 8'd0; snmp_s_sop = 1'b0; snmp_s_eop = 1'b0;
  snmp_m_ready = 1'b1; snmp_src_sel = 1'b0;
  app_msg_valid = 1'b0; app_vl = 7'd0; app_length = 12'd0; app_data = 8'd0;
  app_valid = 1'b0; app_last = 1'b0; app_rsp_ready = 1'b0;
  drop_valid = 1'b0; drop_vl = 7'd0; drop_rsp_ready = 1'b0;
  ext_cfg_valid = 1'b0; ext_cfg_vl = 7'd0; ext_cfg_bag_exp = 3'd0;
  ext_run = 1'b0; app_enable = 1'b0; rx_ready_r = 1'b1;

  repeat (6) @(negedge clk);
  reset = 1'b0;

  wait_i = 0;
  while (!initialized && (wait_i < 400000)) begin
   @(negedge clk);
   wait_i = wait_i + 1;
  end
  check(initialized === 1'b1, 200);
  check(tx_fault === 1'b0, 201);
  $display("PHASE init done at %0d", $time);

  // ---- management bus identity reads ----
  bus_read_expect(A_VERSION, EXP_VERSION, 210);
  bus_read_expect(A_ID, EXP_ID, 211);
  bus_read(A_STATUS);
  check(rd[0] === 1'b0, 212);
  check(rd[1] === 1'b0, 213);
  check(rd[2] === 1'b0, 214);

  // ---- external run is forwarded (OR semantics) ----
  ext_run = 1'b1;
  repeat (4) @(negedge clk);
  check(sys_run === 1'b1, 220);
  check(mgmt_run === 1'b0, 221);
  ext_run = 1'b0;
  repeat (3) @(negedge clk);
  check(sys_run === 1'b0, 222);

  // ---- BAG shadow + commit #1 (BAG exp = 1, 2 ms per VL at 100 MHz) ----
  bus_write(A_BAG_SHADOW, 32'd1);
  bus_read_expect(A_BAG_SHADOW, 32'd1, 230);
  bus_read_expect(A_BAG_ACTIVE, 32'd0, 231);
  bus_write(A_BAG_COMMIT, 32'd1);
  wait_cfg_done(1);
  bus_read_expect(A_BAG_ACTIVE, 32'd1, 232);
  check(cfg_bag_exp_active === 3'd1, 233);
  bus_read(A_STATUS);
  check(rd[1] === 1'b1, 234);

  // ---- BAG shadow + commit #2 (BAG exp = 0), with an external cfg request
  //      held across the management programming window: management wins, the
  //      external request sees cfg_reject and is served afterwards.
  ext_cfg_valid = 1'b1; ext_cfg_vl = 7'd5; ext_cfg_bag_exp = 3'd2;
  bus_write(A_BAG_SHADOW, 32'd0);
  bus_write(A_BAG_COMMIT, 32'd1);
  wait_cfg_done(2);
  check(cfg_done_seen === 2, 235);
  bus_read_expect(A_BAG_ACTIVE, 32'd0, 236);
  check(cfg_bag_exp_active === 3'd0, 237);
  wait_i = 0;
  while (!cfg_ready && (wait_i < 20000)) begin
   @(negedge clk);
   wait_i = wait_i + 1;
  end
  check(cfg_ready === 1'b1, 238);
  check(cfg_reject_seen > 0, 239);
  @(negedge clk); ext_cfg_valid = 1'b0;
  @(negedge clk);
  check(cfg_busy === 1'b0, 240);

  // ---- start the data path from the management run bit only ----
  bus_write(A_CTRL, 32'd1);
  check(mgmt_run === 1'b1, 250);
  check(ext_run === 1'b0, 251);
  check(sys_run === 1'b1, 252);
  bus_read(A_STATUS);
  check(rd[0] === 1'b1, 253);
  app_enable = 1'b1;

  // ---- 16 application frames: 4 VL x lengths 1/17/63/1471 ----
  $display("PHASE send 16 frames at %0d", $time);
  for (vl = 0; vl < 4; vl = vl + 1) begin
   for (kk = 0; kk < 4; kk = kk + 1) begin
    case ((kk + vl) % 4)
     0: send_frame(vl, 1,    -1);
     1: send_frame(vl, 17,   -1);
     2: send_frame(vl, 63,   -1);
     default: send_frame(vl, 1471, -1);
    endcase
   end
  end
  check(sent_frames === 16, 260);
  wait_delivery(16);
  wait_i = 0;
  while ((rejected_frames < 16) && (wait_i < 4000000)) begin
   @(negedge clk);
   wait_i = wait_i + 1;
  end
  check(rejected_frames === 16, 261);
  check(delivered_frames === 16, 262);
  $display("PHASE 16 frames delivered at %0d delivered=%0d rejected=%0d",
           $time, delivered_frames, rejected_frames);

  // ---- 17th frame with a corrupted looped-back payload byte ----
  corrupt_en = 1'b1;
  send_frame(3, 63, -1);
  wait_i = 0;
  while ((bad_fcs_total !== 64'd2) && (wait_i < 400000)) begin
   @(negedge clk);
   wait_i = wait_i + 1;
  end
  check(bad_fcs_total === 64'd2, 270);
  wait_i = 0;
  while (busy && (wait_i < 400000)) begin
   @(negedge clk);
   wait_i = wait_i + 1;
  end
  check(busy === 1'b0, 271);
  check(delivered_frames === 16, 272);
  check(rejected_frames === 16, 273);
  check(tx_frames === 17, 274);
  check(full_drops === 64'd0, 275);
  check(drop_frames === 32'd0, 276);
  corrupt_en = 1'b0;
  repeat (200) @(negedge clk);
  $display("PHASE fault frame done at %0d bad_fcs=%0d tx_frames=%0d",
           $time, bad_fcs_total, tx_frames);

  // ---- management RTC follows the data-path monotonic_time ----
  bus_read(A_RTC_LIVE_NSEC);
  rtc_nsec_1 = rd;
  repeat (100) @(negedge clk);
  bus_read(A_RTC_LIVE_NSEC);
  rtc_nsec_2 = rd;
  check(rtc_nsec_2 > rtc_nsec_1, 280);
  check((rtc_nsec_2 - rtc_nsec_1) >= 95, 281);
  check((rtc_nsec_2 - rtc_nsec_1) <= 120, 282);

  // ---- management counter snapshot and readback ----
  bus_write(A_CTRL, 32'h0000_0003); // keep run=1, snapshot_cmd=1
  check(mgmt_run === 1'b1, 290);
  bus_read_expect(A_SNAP_COUNT, 32'd1, 291);
  bus_read_expect(A_SNAP_DEL, delivered_frames, 292);
  snap_del_v = rd;
  bus_read_expect(A_SNAP_REJ, rejected_frames, 293);
  snap_rej_v = rd;
  bus_read_expect(A_SNAP_DROP, drop_frames, 294);
  snap_drop_v = rd;
  bus_read(A_SNAP_FCS_LO);
  check(rd === bad_fcs_total[31:0], 295);
  snap_fcs_lo_v = rd;
  bus_read(A_SNAP_FCS_HI);
  check(rd === bad_fcs_total[63:32], 296);
  snap_fcs_hi_v = rd;
  bus_read_expect(A_SNAP_TX, tx_frames, 297);
  snap_tx_v = rd;
  bus_read(A_SNAP_SEC_LO);
  check(rd === 32'd0, 298);
  bus_read(A_SNAP_SEC_HI);
  check(rd === 32'd0, 299);
  bus_read(A_SNAP_NSEC);
  check(rd > 32'd1000, 300);
  check(rd < 32'd4000000, 301);
  bus_read(A_STATUS);
  check(rd[0] === 1'b1, 302);
  check(rd[1] === 1'b1, 303);
  check(rd[2] === 1'b1, 304);
  bus_read_expect(A_ERROR_COUNT, 32'd0, 305);
  $display("PHASE snapshot del=%0d rej=%0d drop=%0d fcs_lo=%0d tx=%0d",
           delivered_frames, rejected_frames, drop_frames,
           bad_fcs_total[31:0], tx_frames);

  // ---- SNMP GETs through the direct UDP-payload test port ----
  $display("PHASE snmp direct at %0d", $time);
  snmp_direct(SMG_CASE_DIRECT_IFNUMBER);
  snmp_expect(SMG_CASE_DIRECT_IFNUMBER);
  repeat (20) @(negedge clk);
  snmp_direct(SMG_CASE_DIRECT_INUCAST);
  snmp_expect(SMG_CASE_DIRECT_INUCAST);
  repeat (20) @(negedge clk);

  // ---- SNMP GET routed from the RX application stream ----
  $display("PHASE snmp over RX at %0d", $time);
  snmp_src_sel = 1'b1;
  rx_check_en  = 1'b0;
  repeat (10) @(negedge clk);
  send_frame(2, smg_req_len[SMG_CASE_RX_SYSDESCR], SMG_CASE_RX_SYSDESCR);
  snmp_expect(SMG_CASE_RX_SYSDESCR);
  check(delivered_frames >= 17, 320);
  snmp_src_sel = 1'b0;

  if (errors == 0) begin
   // Report the values read back from the management snapshot (the scenario
   // numbers); the live counters grow by one more frame during the SNMP-over-RX
   // phase that runs after the snapshot assertions.
   $display("TEST_PASS tb_afdx_system_mgmt delivered=%0d rejected=%0d bad_fcs=%0d snap_tx=%0d snmp_direct=2 snmp_rx=1 checks=%0d errors=0",
            snap_del_v, snap_rej_v, {snap_fcs_hi_v, snap_fcs_lo_v}, snap_tx_v, checks);
  end else begin
   $display("TEST_FAIL tb_afdx_system_mgmt errors=%0d checks=%0d", errors, checks);
  end
  $finish;
 end
