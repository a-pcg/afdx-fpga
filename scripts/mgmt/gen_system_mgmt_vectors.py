"""Generate SNMP request/response vectors for tb/tb_afdx_system_mgmt.v.

The integration testbench runs GET requests through the *integrated* management
slice, so the value of counter OIDs depends on what the data path counted.  The
reference encoder/decoder in scripts/mgmt/snmp_client.py is reused here, with an
explicit expected-value override for the counter case:

  case 0  GET ifNumber    1.3.6.1.2.1.2.1.0      -> INTEGER 2 (constant)
  case 1  GET inUcastPkts 1.3.6.1.2.1.2.2.1.11.1 -> Counter32 <in-ucast>
          (<in-ucast> is the mgmt snapshot delivered_frames value the TB asserts,
          default 16 = number of delivered frames in the integration scenario)
  case 2  GET sysDescr    1.3.6.1.2.1.1.1.0      -> OctetString "AFDX dev slice"
          (used on the SNMP-over-RX-application-stream path)

Outputs
  tb/system_mgmt_snmp_vectors.vh                 Verilog include for the TB
  reports/mgmt_integration/snmp_vectors.json     case metadata / hashes

No RTL is modified; this script only produces vectors.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import snmp_client as sc  # noqa: E402

DEFAULT_IN_UCAST = 16

CASES = [
    {"name": "direct_ifnumber", "kind": "get", "oid": (1, 3, 6, 1, 2, 1, 2, 1, 0),
     "rid": 1, "value": None, "note": "constant INTEGER 2"},
    {"name": "direct_inucast", "kind": "get",
     "oid": (1, 3, 6, 1, 2, 1, 2, 2, 1, 11, 1), "rid": 2,
     "value": ("counter", DEFAULT_IN_UCAST),
     "note": "Counter32 of the mgmt snapshot delivered_frames"},
    {"name": "rx_sysdescr", "kind": "get", "oid": (1, 3, 6, 1, 2, 1, 1, 1, 0),
     "rid": 3, "value": None, "note": "constant OctetString"},
]

CASE_CONST = {case["name"]: index for index, case in enumerate(CASES)}


def build_response(request_id, status, index, oid, value_kind, value):
    """Build a complete SNMPv1 response with the client's own BER encoders."""
    varbind = sc.enc_tlv(0x30, sc.enc_oid(oid) + sc.enc_value(value_kind, value))
    pdu_body = (sc.enc_int(request_id) + sc.enc_int(status) + sc.enc_int(index)
                + sc.enc_tlv(0x30, varbind))
    pdu = sc.enc_tlv(0xA2, pdu_body)
    return sc.enc_tlv(0x30, sc.enc_int(0) + sc.enc_tlv(0x04, sc.COMMUNITY) + pdu)


def case_expected(case, in_ucast):
    if case["value"] is not None:
        value_kind, value = case["value"]
        if value_kind == "counter" and case["name"] == "direct_inucast":
            value = in_ucast
        return build_response(case["rid"], 0, 0, case["oid"], value_kind, value)
    return sc.expected_response(case["kind"], case["oid"], case["rid"])


def emit(in_ucast=DEFAULT_IN_UCAST, verbose=True):
    requests = [sc.enc_request(case["kind"], case["oid"], case["rid"]) for case in CASES]
    expected = [case_expected(case, in_ucast) for case in CASES]

    # Self-check: every expected response must decode to the intended fields.
    for case, exp in zip(CASES, expected):
        parsed = sc.decode_response(exp)
        assert parsed["request_id"] == case["rid"], case["name"]
        assert parsed["error_status"] == 0, case["name"]
        assert parsed["oid"] == case["oid"], case["name"]
        if case["value"] is None:
            _, ref_value, _ = sc.BY_OID[case["oid"]]
        else:
            ref_value = in_ucast if case["name"] == "direct_inucast" else case["value"][1]
        assert parsed["value"] == ref_value, (case["name"], parsed["value"], ref_value)

    req_pool = b"".join(requests)
    exp_pool = b"".join(expected)
    req_off, exp_off = [], []
    acc = 0
    for req in requests:
        req_off.append(acc)
        acc += len(req)
    acc = 0
    for exp in expected:
        exp_off.append(acc)
        acc += len(exp)

    lines = [
        "// Generated by scripts/mgmt/gen_system_mgmt_vectors.py -- do not edit.",
        "// SNMPv1 request/expected-response byte tables for tb_afdx_system_mgmt.",
        "// Regenerate with: python scripts/mgmt/gen_system_mgmt_vectors.py --in-ucast %d" % in_ucast,
        "localparam SMG_CASE_COUNT = %d;" % len(CASES),
    ]
    for name, index in CASE_CONST.items():
        lines.append("localparam SMG_CASE_%s = %d;" % (name.upper(), index))
    lines += [
        "localparam SMG_INUCAST_VALUE = %d;" % in_ucast,
        "localparam SMG_REQ_MAX = %d;" % len(req_pool),
        "localparam SMG_EXP_MAX = %d;" % len(exp_pool),
        "reg [7:0] smg_req_bytes [0:SMG_REQ_MAX-1];",
        "reg [7:0] smg_exp_bytes [0:SMG_EXP_MAX-1];",
        "reg [7:0] smg_req_len [0:SMG_CASE_COUNT-1];",
        "reg [7:0] smg_exp_len [0:SMG_CASE_COUNT-1];",
        "reg [31:0] smg_req_off [0:SMG_CASE_COUNT-1];",
        "reg [31:0] smg_exp_off [0:SMG_CASE_COUNT-1];",
        "initial begin",
    ]
    for index, req in enumerate(requests):
        lines.append(" smg_req_off[%d] = %d;" % (index, req_off[index]))
        lines.append(" smg_req_len[%d] = %d;" % (index, len(req)))
    for index, exp in enumerate(expected):
        lines.append(" smg_exp_off[%d] = %d;" % (index, exp_off[index]))
        lines.append(" smg_exp_len[%d] = %d;" % (index, len(exp)))
    for index, value in enumerate(req_pool):
        lines.append(" smg_req_bytes[%d] = 8'h%02x;" % (index, value))
    for index, value in enumerate(exp_pool):
        lines.append(" smg_exp_bytes[%d] = 8'h%02x;" % (index, value))
    lines.append("end")
    include = "\n".join(lines) + "\n"

    include_path = ROOT / "tb/system_mgmt_snmp_vectors.vh"
    # Deterministic LF-only output; hash the bytes actually written so the
    # metadata matches the on-disk file byte-for-byte.
    include_path.write_text(include, encoding="ascii", newline="\n")
    digest = hashlib.sha256(include_path.read_bytes()).hexdigest()

    meta = {
        "generator": "scripts/mgmt/gen_system_mgmt_vectors.py",
        "in_ucast_value": in_ucast,
        "include": "tb/system_mgmt_snmp_vectors.vh",
        "include_sha256": digest,
        "include_bytes": len(include),
        "community": sc.COMMUNITY.decode(),
        "cases": [
            {"index": index, "name": case["name"], "kind": case["kind"],
             "oid": ".".join(str(x) for x in case["oid"]),
             "request_id": case["rid"],
             "request_bytes": len(req), "expected_bytes": len(exp),
             "note": case["note"]}
            for index, (case, req, exp) in enumerate(zip(CASES, requests, expected))
        ],
        "total_request_bytes": len(req_pool),
        "total_expected_bytes": len(exp_pool),
    }
    report = ROOT / "reports/mgmt_integration"
    report.mkdir(parents=True, exist_ok=True)
    (report / "snmp_vectors.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    if verbose:
        for index, (case, req, exp) in enumerate(zip(CASES, requests, expected)):
            print("VECTOR case=%d %-16s oid=%s request=%d expected=%d"
                  % (index, case["name"], ".".join(str(x) for x in case["oid"]),
                     len(req), len(exp)))
        print("VECTORS_WRITTEN include=%s cases=%d request_bytes=%d expected_bytes=%d sha256=%s"
              % (include_path, len(CASES), len(req_pool), len(exp_pool), digest[:16]))
    return meta


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--in-ucast", type=int, default=DEFAULT_IN_UCAST,
                    help="expected Counter32 value for the inUcastPkts GET (default 16)")
    args = ap.parse_args()
    emit(args.in_ucast)
