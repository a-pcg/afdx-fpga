"""Single source of truth for the T11 50 MHz / 100 Mbps candidate time base.

Only two elaboration pairs are legal in this round:
  compat100 : 100 MHz core, 8 core cycles per byte  (old behaviour, default)
  cand50    :  50 MHz core, 4 core cycles per byte  (100 Mbps nominal line rate)
All simulation parameters, BAG expectations, timeouts and unit conversions are
derived here so no test hard-codes its own constants.
"""
from pathlib import Path
import json

CONFIGS = {
    'compat100': {'core_clk_hz': 100_000_000, 'byte_cycles': 8, 'tag': 't11_compat_100m8'},
    'cand50':    {'core_clk_hz':  50_000_000, 'byte_cycles': 4, 'tag': 't11_50m4'},
}
ALLOWED = {(100_000_000, 8), (50_000_000, 4)}
NOMINAL_BIT_RATE = 100_000_000


def validate(core_clk_hz, byte_cycles):
    if (core_clk_hz, byte_cycles) not in ALLOWED:
        raise SystemExit('rejected configuration: CORE_CLK_HZ=%d BYTE_CYCLES=%d (only 100e6/8 and 50e6/4 are legal this round)'
                         % (core_clk_hz, byte_cycles))
    if core_clk_hz % 1000:
        raise SystemExit('CORE_CLK_HZ must be a multiple of 1000')
    if core_clk_hz * 8 // byte_cycles != NOMINAL_BIT_RATE:
        raise SystemExit('byte rhythm does not give a 100 Mbit/s nominal line rate')
    if not (1 <= byte_cycles <= 8):
        raise SystemExit('BYTE_CYCLES out of range')


def config(name):
    if name not in CONFIGS:
        raise SystemExit('unknown run config %r (choices: %s)' % (name, ', '.join(sorted(CONFIGS))))
    base = dict(CONFIGS[name])
    core, byte = base['core_clk_hz'], base['byte_cycles']
    validate(core, byte)
    cpm = core // 1000
    cfg = dict(base)
    cfg.update({
        'cycles_per_ms': cpm,
        'ns_per_cycle': 1e9 / core,
        'cycles_per_byte': byte,
        'ns_per_byte': byte * 1e9 / core,
        'line_bytes_per_s': core / byte,
        'nominal_bit_rate': 8.0 * core / byte,
        'line_bytes_per_ms': int(core / byte / 1000),
        'skew_max_cycles': cpm,             # 1 ms skew window (development default)
        'rm_resync_timeout_cycles': 10 * cpm,  # 10 ms resync interval (development default)
        'bag_cycles': {e: cpm << e for e in range(8)},
        'ifg_cycles': 12 * byte,
        'ifg_ns': 12 * byte * 1e9 / core,
    })
    return cfg


def verilator_parameters(cfg):
    return {'CORE_CLK_HZ': cfg['core_clk_hz'], 'BYTE_CYCLES': cfg['byte_cycles']}


def describe(cfg):
    return {
        'config': cfg['tag'],
        'core_clk_hz': cfg['core_clk_hz'],
        'byte_cycles': cfg['byte_cycles'],
        'cycles_per_ms': cfg['cycles_per_ms'],
        'ns_per_cycle': cfg['ns_per_cycle'],
        'ns_per_byte': cfg['ns_per_byte'],
        'nominal_bit_rate': cfg['nominal_bit_rate'],
        'line_bytes_per_ms': cfg['line_bytes_per_ms'],
        'skew_max_cycles': cfg['skew_max_cycles'],
        'rm_resync_timeout_cycles': cfg['rm_resync_timeout_cycles'],
        'bag_cycles': cfg['bag_cycles'],
        'ifg_cycles': cfg['ifg_cycles'],
        'ifg_ns': cfg['ifg_ns'],
        'verilator_parameters': verilator_parameters(cfg),
    }


def write_header(cfg, path):
    """Generate the C++ header consumed by the config-driven testbenches."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '// generated by scripts/system_integration/run_config.py - do not edit',
        '#ifndef RCFG_H',
        '#define RCFG_H',
        '#define RCFG_NAME "%s"' % cfg['tag'],
        '#define RCFG_CORE_CLK_HZ %d' % cfg['core_clk_hz'],
        '#define RCFG_BYTE_CYCLES %d' % cfg['byte_cycles'],
        '#define RCFG_CYCLES_PER_MS %d' % cfg['cycles_per_ms'],
        '#define RCFG_NS_PER_CYCLE %.6f' % cfg['ns_per_cycle'],
        '#define RCFG_NS_PER_BYTE %.6f' % cfg['ns_per_byte'],
        '#define RCFG_NOMINAL_BIT_RATE %.6f' % cfg['nominal_bit_rate'],
        '#define RCFG_LINE_BYTES_PER_MS %d' % cfg['line_bytes_per_ms'],
        '#define RCFG_IFG_CYCLES %d' % cfg['ifg_cycles'],
        '#define RCFG_IFG_NS %.6f' % cfg['ifg_ns'],
        '#define RCFG_SKEW_MAX_CYCLES %d' % cfg['skew_max_cycles'],
        '#define RCFG_RM_RESYNC_TIMEOUT_CYCLES %d' % cfg['rm_resync_timeout_cycles'],
        '#endif',
        '',
    ]
    path.write_text('\n'.join(lines), encoding='utf-8')
    return path


def parse_wrapper_parameters(path):
    """Read the elaboration parameters fixed in an E5 wrapper source file."""
    import re
    text = Path(path).read_text(encoding='utf-8', errors='replace')
    core = re.search(r"CORE_CLK_HZ\s*=\s*\d+'d\s*(\d+)", text)
    byte = re.search(r"BYTE_CYCLES\s*=\s*\d+'d\s*(\d+)", text)
    if not core or not byte:
        raise SystemExit('wrapper %s does not fix CORE_CLK_HZ / BYTE_CYCLES localparams' % path)
    core_clk_hz = int(core.group(1))
    byte_cycles = int(byte.group(1))
    validate(core_clk_hz, byte_cycles)
    return {
        'core_clk_hz': core_clk_hz,
        'byte_cycles': byte_cycles,
        'cycles_per_ms': core_clk_hz // 1000,
        'required_period_ns': 1e9 / core_clk_hz,
        'ns_per_byte': byte_cycles * 1e9 / core_clk_hz,
        'source': str(Path(path).as_posix()),
    }


if __name__ == '__main__':
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--config', default='compat100', choices=sorted(CONFIGS))
    ap.add_argument('--header', type=Path)
    a = ap.parse_args()
    c = config(a.config)
    if a.header:
        write_header(c, a.header)
    print(json.dumps(describe(c), indent=2))
